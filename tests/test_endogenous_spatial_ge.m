function test_endogenous_spatial_ge()
%TEST_ENDOGENOUS_SPATIAL_GE Verify Solve_Spatial_GE_Loop (NZ & FI) and non-proportional 5D T2/T3 integrals.

repo_root = fileparts(fileparts(mfilename('fullpath')));
addpath(repo_root);
setup_igw_paths(true);

%% 1. NZ_Dunedin1972 & FI_Peruskoulu1967 Endogenous Spatial GE Clearing (< 0.05s)
for prof_cell = {'NZ_Dunedin1972', 'FI_Peruskoulu1967'}
    prof_id = prof_cell{1};
    P0      = Configure_Model_Params(struct('Profile_Name', prof_id, 'dt', 3));
    Specs   = Default_Reform_Phase_Specs(P0, true);

    check(isempty(Specs(1).w_mult_vs_SS0) && isempty(Specs(1).Q_mult_vs_SS0), ...
        sprintf('[%s] Default_Reform_Phase_Specs must leave w_mult/Q_mult empty for endogenous solving.', prof_id));
    check(abs(Specs(1).tau_a_firm - 0.015) < 1e-12 && abs(Specs(1).tau_k_firm - 0.120) < 1e-12, ...
        sprintf('[%s] Expected Guvenen firm tax rotation (tau_a=0.015, tau_k=0.120).', prof_id));

    GE1 = Solve_Spatial_GE_Loop(P0, Specs(1), struct('PhaseIdx', 1));
    GE2 = Solve_Spatial_GE_Loop(P0, Specs(2), struct('PhaseIdx', 2));

    % Guvenen Use-It-Or-Lose-It: z_h equity share and TFP must strictly expand in all 4 regions
    check(all(GE1.zh_eq_share_Ref > GE1.zh_eq_share_SS0) && all(GE1.Z_tfp_ratio_vec > 1.0), ...
        sprintf('[%s] Guvenen z_h equity share and TFP failed to expand in SS1.', prof_id));
    check(all(GE2.w_mult_vec > GE1.w_mult_vec) && all(GE1.w_mult_vec > 1.02), ...
        sprintf('[%s] Endogenous wages must satisfy 1.02 < w_SS1 < w_SS2 across all regions.', prof_id));

    % Hirano-Toda + delta_H Housing Capitalization: Primate city (inelastic delta_H) cools strictly more than Rural
    check(all(GE1.Q_mult_vec < 1.0) && all(GE2.Q_mult_vec < GE1.Q_mult_vec), ...
        sprintf('[%s] Endogenous Q_mult must cool in SS1 and cool further in SS2.', prof_id));
    check(GE2.Q_mult_vec(end) < GE2.Q_mult_vec(1) - 0.05, ...
        sprintf('[%s] Primate metro Q_k must cool by >5pp more than elastic Rural.', prof_id));

    % Duffy / Monopsony Relief: Rural/Small Rouwenhorst drift exceeds Primate Metro
    check(GE2.d_mu_z_vec(1) > GE2.d_mu_z_vec(end) && all(GE2.p_zh_upgrade_vec > 0.15), ...
        sprintf('[%s] Competition-driven d_mu_z and firm upgrade rate failed spatial gradient.', prof_id));
end

%% 2. Verify T2 (Quintiles) & T3 (Tenure) Are Genuine 5D Integrals (NOT Fixed Proportionality Multiples!)
if exist('ValueFnIter_MixHorz_PType', 'file') ~= 0
    P_m    = Configure_Model_Params(struct('Profile_Name', 'NZ_Dunedin1972', 'dt', 15, 'n_z_pts', 2));
    Regs_m = P_m.Regions;
    Names_i = [cellfun(@(r) ['HH_', r], Regs_m, 'UniformOutput', false), ...
               cellfun(@(r) ['Firm_', r], Regs_m, 'UniformOutput', false)];
    P_m.PTypeWeights = [0.90 * P_m.Pop_Weights_4(:); 0.10 * P_m.Firm_Weights_4(:)];
    P_m.mewj         = ones(1, P_m.J) / P_m.J;

    hh5dFn = @(l, Ih, ic, aprime, hprime, a, h, theta_c, z, ...
        w_reg, r, Q_reg, G_reg, phi_nd, mu_maint, upsilon_h, chi_bar, ebar_energy, ...
        Transfer_Geo, p_super, c_floor, G_ece_stage1, G_ece_stage2, gbar_ece, s_sub, ...
        omega_ic, gamma1_self, gamma1_inv, gamma1_par, phi1_ces, ...
        gamma2_self, gamma2_inv, gamma2_par, phi2_ces, ...
        delta_hc, alpha_I, alpha_H, b1_beq, b2_beq, YouthGrant, ...
        tau_l, tau_c, tau_k, tau_a, tau_b, agej, Jr, sj, dt, ...
        j_s1_start, j_s1_end, j_s2_start, j_s2_end, n_stage1_steps, n_stage2_steps, ...
        Q_reg_base, K_whanau) ...
        ReturnFn_SpatialHH(l, Ih, ic, aprime, hprime, a, h, theta_c, z, ...
        w_reg, r, Q_reg, G_reg, phi_nd, mu_maint, upsilon_h, chi_bar, ebar_energy, ...
        Transfer_Geo, p_super, c_floor, G_ece_stage1, G_ece_stage2, gbar_ece, s_sub, ...
        omega_ic, gamma1_self, gamma1_inv, gamma1_par, phi1_ces, ...
        gamma2_self, gamma2_inv, gamma2_par, phi2_ces, ...
        delta_hc, alpha_I, alpha_H, b1_beq, b2_beq, YouthGrant, ...
        tau_l, tau_c, tau_k, tau_a, tau_b, agej, Jr, sj, dt, ...
        j_s1_start, j_s1_end, j_s2_start, j_s2_end, n_stage1_steps, n_stage2_steps, ...
        Q_reg_base, K_whanau);

    apFn = @(i_c, thetac, agej, phi1_ces, gamma1_self, gamma1_inv, gamma1_par, G_ece_stage1, ...
        phi2_ces, gamma2_self, gamma2_inv, gamma2_par, G_ece_stage2, gbar_ece, h_par_mean, ...
        j_s1_start, j_s1_end, j_s2_start, j_s2_end, n_stage1_steps, n_stage2_steps, ...
        Q_reg, Q_reg_base, K_whanau, Jr, dt) ...
        HumanCapital_Lifecycle_aprimeFn(i_c, thetac, agej, phi1_ces, gamma1_self, gamma1_inv, gamma1_par, G_ece_stage1, ...
        phi2_ces, gamma2_self, gamma2_inv, gamma2_par, G_ece_stage2, gbar_ece, h_par_mean, ...
        j_s1_start, j_s1_end, j_s2_start, j_s2_end, n_stage1_steps, n_stage2_steps, ...
        Q_reg, Q_reg_base, K_whanau, Jr, dt);

    for r = 1:numel(Regs_m)
        ht = ['HH_', Regs_m{r}]; ft = ['Firm_', Regs_m{r}];
        N_j.(ht) = P_m.J; N_j.(ft) = Inf;
        n_d.(ht) = [2, 2, 2]; d_grid.(ht) = [0; 1.0; 0; 0.2; 0; 0.3];
        n_a.(ht) = [5, 3, 2]; a_grid.(ht) = [[0; 0.3; 1.2; 3.5; 8.0]; [0.6; 1.0; 1.5]; [0.75; 1.25]];
        n_z.(ht) = 2; z_grid.(ht) = [0.85; 1.15]; pi_z.(ht) = [0.8, 0.2; 0.2, 0.8];
        n_d.(ft) = 0; d_grid.(ft) = []; n_a.(ft) = 5; a_grid.(ft) = linspace(0.5, 10, 5)';
        n_z.(ft) = 2; z_grid.(ft) = [0.8; 1.3]; pi_z.(ft) = [0.85, 0.15; 0.15, 0.85];
        DiscountFactorParamNames.(ht) = {'beta_hh', 'sj'};
        DiscountFactorParamNames.(ft) = {'beta_firm'};
        vfoptions.experienceasset.(ht) = 1; vfoptions.aprimeFn.(ht) = apFn; vfoptions.experienceasset.(ft) = 0;
        simoptions.experienceasset.(ht)= 1; simoptions.aprimeFn.(ht)= apFn; simoptions.experienceasset.(ft)= 0;
        ReturnFn.(ht) = hh5dFn;
        ReturnFn.(ft) = @(aprime,a,z,w_reg,r,alpha_k,lambda_col,delta_k,tau_k,tau_a,dt) ReturnFn_Firm(aprime,a,z,w_reg,r,alpha_k,lambda_col,delta_k,tau_k,tau_a,dt);
        jDist_init.(ht) = ones([n_a.(ht), n_z.(ht)]) / prod([n_a.(ht), n_z.(ht)]);
    end
    vfoptions.verbose = 0; vfoptions.vectorized = 1;
    simoptions.verbose = 0; simoptions.d_grid = d_grid; simoptions.a_grid = a_grid;

    Grids5D = struct('n_d', n_d, 'n_a', n_a, 'n_z', n_z, 'N_j', N_j, 'Names_i', {Names_i}, ...
        'd_grid', d_grid, 'a_grid', a_grid, 'z_grid', z_grid, 'pi_z', pi_z, 'ReturnFn', ReturnFn, ...
        'DiscountFactorParamNames', {DiscountFactorParamNames}, 'AgeWeightsParamNames', {{'mewj'}}, ...
        'PTypeDistParamNames', {{'PTypeWeights'}}, 'vfoptions', vfoptions, 'simoptions', simoptions);

    Decomp = Compute_WelfareDecomposition_4Region(P_m, Grids5D, jDist_init, ...
        struct('Enable_SS2_Phase', false, 'Verbose', false, 'MaxIGIter_SS0', 3, 'MaxIGIter_SSm', 3));

    t2_mat = table2array(Decomp.T2);
    t3_mat = table2array(Decomp.T3);
    check(all(isfinite(t2_mat(:))) && all(isfinite(t3_mat(:))), 'T2 or T3 contains non-finite entries.');

    % Verify T3 rows across Rural vs Auckland are NOT collinear constant multiples (retired [1.38; 0.94; 0.42]):
    ratio_rur = t3_mat(1, 1) / max(1e-8, t3_mat(3, 1));
    ratio_akl = t3_mat(1, 4) / max(1e-8, t3_mat(3, 4));
    check(abs(ratio_rur - ratio_akl) > 1e-4, ...
        'T3 renter-to-retiree ratio is identical across Rural and Auckland (expected state-space variation).');
end
end

function check(cond, msg)
if ~cond
    error('IGW:TestFailure', 'test_endogenous_spatial_ge: %s', msg);
end
end
