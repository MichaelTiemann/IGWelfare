function htmlStr = buildNarrativeHTML(srcLabel, tgtLabel, flowVal, sNum, tNum, narrativeMap, valFmtStr)
    narEntry = [];
    keyArrow = sprintf('%d->%d', sNum, tNum);
    keyUnder = sprintf('n_%d_%d', sNum, tNum);
    if isa(narrativeMap, 'containers.Map')
        if isKey(narrativeMap, keyArrow)
            narEntry = narrativeMap(keyArrow);
        elseif isKey(narrativeMap, sprintf('%d_%d', sNum, tNum))
            narEntry = narrativeMap(sprintf('%d_%d', sNum, tNum));
        end
    elseif isstruct(narrativeMap) && isfield(narrativeMap, keyUnder)
        narEntry = narrativeMap.(keyUnder);
    end

    hdrHtml = sprintf('<div class="hb-hdr">[%s] &rarr; [%s]</div>', ...
        htmlEscape(srcLabel), htmlEscape(tgtLabel));
    flowStr = sprintf(valFmtStr, flowVal);

    if ~isempty(narEntry)
        if isstruct(narEntry)
            tStr = ''; mStr = ''; cStr = '';
            if isfield(narEntry, 'title'),     tStr = strtrim(char(narEntry.title));     end
            if isfield(narEntry, 'mechanism'), mStr = strtrim(char(narEntry.mechanism)); end
            if isfield(narEntry, 'citation'),  cStr = strtrim(char(narEntry.citation));  end

            if ~isempty(tStr)
                fHtml = sprintf('<div class="hb-row">&bull; <b>Flow:</b> %s &nbsp;|&nbsp; %s</div>', ...
                    htmlEscape(flowStr), htmlEscape(tStr));
            else
                fHtml = sprintf('<div class="hb-row">&bull; <b>Flow:</b> %s</div>', htmlEscape(flowStr));
            end
            mHtml = sprintf('<div class="hb-row">&bull; <b>Mechanism:</b> %s</div>', htmlEscape(mStr));
            cHtml = formatCitationsHTML(cStr);
            htmlStr = [hdrHtml, fHtml, mHtml, cHtml];
        else
            if iscell(narEntry)
                rawLines = cellstr(string(narEntry(:)))';
            else
                rawLines = cellstr(splitlines(string(narEntry)))';
            end
            fHtml = sprintf('<div class="hb-row">&bull; <b>Flow:</b> %s</div>', htmlEscape(flowStr));
            bHtml = '';
            for rL = 1:numel(rawLines)
                lin = strtrim(rawLines{rL});
                if isempty(lin), continue; end
                if contains(lin, 'Citation:', 'IgnoreCase', true) || contains(lin, 'Ref:', 'IgnoreCase', true)
                    cClean = regexprep(lin, '^[•\-\s]*(Citation|Ref|References)\s*:\s*', '', 'ignorecase');
                    bHtml = [bHtml, formatCitationsHTML(cClean)]; %#ok<AGROW>
                else
                    bHtml = [bHtml, sprintf('<div class="hb-row">%s</div>', htmlEscape(lin))]; %#ok<AGROW>
                end
            end
            htmlStr = [hdrHtml, fHtml, bHtml];
        end
    else
        fHtml = sprintf('<div class="hb-row">&bull; <b>Flow:</b> %s &nbsp;|&nbsp; Node %d &rarr; Node %d</div>', ...
            htmlEscape(flowStr), sNum, tNum);
        htmlStr = [hdrHtml, fHtml];
    end
end

function cHtml = formatCitationsHTML(citStr)
    citStr = strtrim(char(citStr));
    if isempty(citStr)
        cHtml = '';
        return;
    end
    parts = strtrim(strsplit(citStr, ';'));
    parts = parts(~cellfun(@isempty, parts));
    if numel(parts) <= 1
        cHtml = sprintf('<div class="hb-row">&bull; <b>Citation:</b> %s</div>', htmlEscape(parts{1}));
    else
        cHtml = sprintf('<div class="hb-row">&bull; <b>Citations:</b> %s;</div>', htmlEscape(parts{1}));
        for p = 2:numel(parts)
            sfx = ';';
            if p == numel(parts), sfx = ''; end
            cHtml = [cHtml, sprintf('<div class="hb-cit">%s%s</div>', htmlEscape(parts{p}), sfx)]; %#ok<AGROW>
        end
    end
end

function [xc, yt, yb, ym, x1, y1, x2, y2] = getTrueAlignedRibbonRails(hP)
    X = double(hP.XData);
    Y = double(hP.YData);
    if size(X, 1) == 2 && size(X, 2) > 1
        x1 = X(1, :);  y1 = Y(1, :);
        x2 = X(2, :);  y2 = Y(2, :);
        nPts = size(X, 2);
    elseif size(X, 2) == 2 && size(X, 1) > 1
        x1 = X(:, 1)'; y1 = Y(:, 1)';
        x2 = X(:, 2)'; y2 = Y(:, 2)';
        nPts = size(X, 1);
    else
        xv = X(:)';    yv = Y(:)';
        nHalf = floor(numel(xv) / 2);
        x1 = xv(1:nHalf);             y1 = yv(1:nHalf);
        x2 = fliplr(xv(nHalf+1:end)); y2 = fliplr(yv(nHalf+1:end));
        nPts = nHalf;
    end
    xL = min([x1(:); x2(:)]);
    xR = max([x1(:); x2(:)]);
    xc = linspace(xL, xR, nPts);
    yt = zeros(1, nPts);
    yb = zeros(1, nPts);
    for k = 1:nPts
        [~, i1] = min(abs(x1 - xc(k)));
        [~, i2] = min(abs(x2 - xc(k)));
        yt(k) = max(y1(i1), y2(i2));
        yb(k) = min(y1(i1), y2(i2));
    end
    ym = 0.5 * (yt + yb);
end

function rgb = getBlockRGB(SK, bIdx)
    rgb = [0.30, 0.50, 0.60];
    try
        if isprop(SK, 'ColorList') && size(SK.ColorList, 1) >= bIdx
            rgb = double(SK.ColorList(bIdx, 1:3));
            return;
        end
        if isgraphics(SK.BlockHdl(bIdx))
            fc = SK.BlockHdl(bIdx).FaceColor;
            if isnumeric(fc) && numel(fc) == 3
                rgb = double(fc(:)');
            end
        end
    catch
    end
end

function hexStr = rgbToHex(rgb)
    if ~isnumeric(rgb) || numel(rgb) < 3
        hexStr = '#333333';
        return;
    end
    c = round(255 * max(0, min(1, double(rgb(1:3)))));
    hexStr = sprintf('#%02x%02x%02x', c(1), c(2), c(3));
end

function linesCell = formatTextLines(strIn)
    if isempty(strIn)
        linesCell = {};
    elseif iscell(strIn)
        linesCell = cellstr(string(strIn(:)))';
    else
        linesCell = cellstr(splitlines(string(strIn)))';
    end
    linesCell = linesCell(~cellfun(@(s) isempty(strtrim(s)), linesCell));
end

function out = htmlEscape(str)
    out = char(str);
    out = strrep(out, '&', '&amp;');
    out = strrep(out, '<', '&lt;');
    out = strrep(out, '>', '&gt;');
    out = strrep(out, '"', '&quot;');
end

function num = extractNodeNumber(str)
    tok = regexp(str, '^(\d+)\.', 'tokens', 'once');
    if ~isempty(tok)
        num = str2double(tok{1});
    else
        num = 0;
    end
end
