function exportSankeyToHTML(axHdl, SK, linksCell, narrativeMap, valFmtStr, outHtmlFile)
% exportSankeyToHTML Exports a live MATLAB SSankey axes into a standalone,
% zero-dependency interactive HTML5 + SVG webpage with identical click,
% narrative callout, bold endpoint legend, and arrow-key traversal behavior.

    if nargin < 5 || isempty(valFmtStr)
        valFmtStr = '%.2f';
    end
    if nargin < 6 || isempty(outHtmlFile)
        outHtmlFile = fullfile(pwd, 'Interactive_Sankey.html');
    end
    if isempty(axHdl) || ~isgraphics(axHdl)
        return;
    end

    % 1. Canvas & Coordinate Mapping (Axes Data Units -> 1850 x 820 SVG ViewBox)
    svgW = 1850;
    svgH = 820;
    padL = 35;  padR = 45;
    padT = 68;  padB = 35;
    plotW = svgW - padL - padR;
    plotH = svgH - padT - padB;

    xl = double(axHdl.XLim);
    yl = double(axHdl.YLim);

    toSvgX = @(x) padL + ((double(x) - xl(1)) ./ diff(xl)) .* plotW;
    % Note: SVG Y=0 is at the TOP, whereas MATLAB YDir='normal' has YIncreasing UPWARD
    toSvgY = @(y) padT + (1.0 - ((double(y) - yl(1)) ./ diff(yl))) .* plotH;

    % 2. Extract Chart Title
    chartTitle = '';
    if ~isempty(axHdl.Title) && isgraphics(axHdl.Title)
        tRaw = axHdl.Title.String;
        if iscell(tRaw), tRaw = strjoin(tRaw, ' '); end
        chartTitle = strtrim(char(tRaw));
    end

    % 3. Extract Node Blocks (SK.BlockHdl) & Match Node Labels
    nBlocks  = numel(SK.BlockHdl);
    blkBBox  = nan(nBlocks, 4); % [svgXMin, svgXMax, svgYMin, svgYMax]
    blkAxBox = nan(nBlocks, 4); % [axXMin, axXMax, axYMin, axYMax]
    blkColor = zeros(nBlocks, 3);

    for b = 1:nBlocks
        if isgraphics(SK.BlockHdl(b))
            bx = double(SK.BlockHdl(b).XData(:));
            by = double(SK.BlockHdl(b).YData(:));
            blkAxBox(b, :) = [min(bx), max(bx), min(by), max(by)];
            sx = toSvgX(bx);
            sy = toSvgY(by);
            blkBBox(b, :)  = [min(sx), max(sx), min(sy), max(sy)];
            blkColor(b, :) = getBlockRGB(SK, b);
        end
    end

    blkXMid = 0.5 * (blkAxBox(:, 1) + blkAxBox(:, 2));
    blkYMid = 0.5 * (blkAxBox(:, 3) + blkAxBox(:, 4));
    [~, ~, blkGateCol] = uniquetol(blkXMid, 0.25, 'DataScale', 1);

    % Identify all visible text objects on the axes (excluding title & hoverBox)
    allTxts = findall(axHdl, 'Type', 'text', 'Visible', 'on');
    blkLblIdx = zeros(nBlocks, 1);

    % Match each block b to its text object via SK.NodeList{b}
    txtList = gobjects(0);
    for t = 1:numel(allTxts)
        tx = allTxts(t);
        if tx == axHdl.Title || strcmp(tx.Tag, 'SSankeyHoverBox')
            continue;
        end
        txtList(end+1) = tx; %#ok<AGROW>
    end

    for b = 1:nBlocks
        if isprop(SK, 'NodeList') && b <= numel(SK.NodeList)
            targetStr = strtrim(regexprep(char(SK.NodeList{b}), '\s+', ' '));
            for t = 1:numel(txtList)
                candStr = formatTextLines(txtList(t).String);
                candFlat = strtrim(regexprep(strjoin(candStr, ' '), '\s+', ' '));
                if strcmp(targetStr, candFlat)
                    blkLblIdx(b) = t;
                    break;
                end
            end
        end
    end

    % 4. Extract Ribbon Links (SK.LinkHdl) + Aligned Centerlines + Narratives
    nLinks = numel(SK.LinkHdl);
    if isprop(SK, 'BoolMat') && ~isempty(SK.BoolMat)
        [sIndVec, tIndVec] = find(SK.BoolMat);
    elseif isprop(SK, 'AdjMat') && ~isempty(SK.AdjMat)
        [sIndVec, tIndVec] = find(SK.AdjMat ~= 0);
    else
        sIndVec = zeros(nLinks, 1);
        tIndVec = zeros(nLinks, 1);
    end

    ribbonsData = cell(1, nLinks);
    svgDefs     = {};
    svgRibbons  = {};

    for k = 1:nLinks
        hP = SK.LinkHdl(k);
        if ~isgraphics(hP), continue; end

        [xg, yt, yb, ym, x1, y1, x2, y2] = getTrueAlignedRibbonRails(hP);
        sBlk = 0; tBlk = 0;
        if k <= numel(sIndVec)
            sBlk = sIndVec(k);
            tBlk = tIndVec(k);
        end

        cS = [0.25, 0.50, 0.65];
        cT = [0.25, 0.50, 0.65];
        if sBlk > 0, cS = blkColor(sBlk, :); end
        if tBlk > 0, cT = blkColor(tBlk, :); end

        % Build SVG linearGradient for ribbon k
        svgDefs{end+1} = sprintf( ...
            '<linearGradient id="grad_%d" x1="0%%" y1="0%%" x2="100%%" y2="0%%"><stop offset="0%%" stop-color="%s"/><stop offset="100%%" stop-color="%s"/></linearGradient>', ...
            k, rgbToHex(cS), rgbToHex(cT)); %#ok<AGROW>

        % Build SVG <path> polygon from upper rail (x1,y1) and reversed lower rail (x2,y2)
        px = toSvgX([x1(:); flipud(x2(:))]);
        py = toSvgY([y1(:); flipud(y2(:))]);
        coords = sprintf('%.2f,%.2f ', [px(:)'; py(:)']);
        pathD  = ['M ', strtrim(coords), ' Z'];

        svgRibbons{end+1} = sprintf( ...
            '<path id="rib_%d" class="sankey-ribbon" data-idx="%d" d="%s" fill="url(#grad_%d)" fill-opacity="0.45"/>', ...
            k, k, pathD, k); %#ok<AGROW>

        % Match row in linksCell & format narrative lines
        rowK = min(k, size(linksCell, 1));
        if sBlk > 0 && tBlk > 0 && isprop(SK, 'NodeList')
            sName = SK.NodeList{sBlk};
            tName = SK.NodeList{tBlk};
            mRow  = find(strcmp(linksCell(:, 1), sName) & strcmp(linksCell(:, 2), tName), 1);
            if ~isempty(mRow), rowK = mRow; end
        end

        srcLabel = strrep(char(linksCell{rowK, 1}), newline, ' ');
        tgtLabel = strrep(char(linksCell{rowK, 2}), newline, ' ');
        flowVal  = linksCell{rowK, 3};
        sNum     = extractNodeNumber(srcLabel);
        tNum     = extractNodeNumber(tgtLabel);

        narLines = buildNarrativeHTML(srcLabel, tgtLabel, flowVal, sNum, tNum, narrativeMap, valFmtStr);

        rStruct = struct();
        rStruct.idx     = k;
        rStruct.srcBlk  = sBlk;
        rStruct.tgtBlk  = tBlk;
        rStruct.srcLbl  = blkLblIdx(max(1, sBlk));
        rStruct.tgtLbl  = blkLblIdx(max(1, tBlk));
        rStruct.xMidAx  = 0.5 * (xg(1) + xg(end));
        rStruct.svgX    = round(toSvgX(xg), 2);
        rStruct.svgYTop = round(toSvgY(yt), 2); % Note: in SVG, top edge has SMALLER Y!
        rStruct.svgYBot = round(toSvgY(yb), 2); % Bottom edge has LARGER Y!
        rStruct.svgYMid = round(toSvgY(ym), 2);
        rStruct.cS      = round(255 * cS);
        rStruct.cT      = round(255 * cT);
        rStruct.html    = narLines;
        ribbonsData{k}  = rStruct;
    end

    % 5. Build SVG Node Block Rectangles
    svgBlocks = {};
    for b = 1:nBlocks
        if ~isnan(blkBBox(b, 1))
            bx1 = blkBBox(b, 1); bx2 = blkBBox(b, 2);
            by1 = blkBBox(b, 3); by2 = blkBBox(b, 4);
            svgBlocks{end+1} = sprintf( ...
                '<rect id="blk_%d" class="sankey-block" data-blk="%d" x="%.2f" y="%.2f" width="%.2f" height="%.2f" fill="%s" stroke="#333" stroke-width="0.6"/>', ...
                b, b, bx1, by1, max(1, bx2 - bx1), max(1, by2 - by1), rgbToHex(blkColor(b, :))); %#ok<AGROW>
        end
    end

    % 6. Serialize Extra Axes Patches & Lines (Wiggly Gate-4 Line, J-Axis, Net-Zero Lines)
    svgLines = {};
    allLines = flipud(findall(axHdl, 'Type', 'line', 'Visible', 'on'));
    for m = 1:numel(allLines)
        ln = allLines(m);
        if ismember(ln.Tag, {'SSankeyLeaderLine', 'SSankeyAnchorDot', 'SSankeyThinSpine'})
            continue;
        end
        lx = double(ln.XData(:));
        ly = double(ln.YData(:));
        valid = ~isnan(lx) & ~isnan(ly);
        lx = lx(valid); ly = ly(valid);
        if isempty(lx), continue; end

        sx = toSvgX(lx);
        sy = toSvgY(ly);
        colHex = rgbToHex(ln.Color);
        lw     = max(0.8, double(ln.LineWidth));

        if numel(lx) >= 2 && ~strcmp(ln.LineStyle, 'none')
            pts = sprintf('%.2f,%.2f ', [sx(:)'; sy(:)']);
            dashAttr = '';
            if strcmp(ln.LineStyle, '--')
                dashAttr = ' stroke-dasharray="7,5"';
            elseif strcmp(ln.LineStyle, ':')
                dashAttr = ' stroke-dasharray="2.5,3.5"';
            elseif strcmp(ln.LineStyle, '-.')
                dashAttr = ' stroke-dasharray="8,3,2,3"';
            end
            svgLines{end+1} = sprintf( ...
                '<polyline points="%s" fill="none" stroke="%s" stroke-width="%.2f" stroke-linecap="round" stroke-linejoin="round"%s pointer-events="none"/>', ...
                strtrim(pts), colHex, lw, dashAttr); %#ok<AGROW>
        end

        % Render markers if present (e.g. circles/squares on Net-Zero Breakeven line)
        if strcmp(ln.Marker, 'o') || strcmp(ln.Marker, 's')
            mFace = ln.MarkerFaceColor;
            if ~isnumeric(mFace), mFace = ln.Color; end
            mEdge = ln.MarkerEdgeColor;
            if ~isnumeric(mEdge), mEdge = [0.1, 0.1, 0.1]; end
            mRad = max(3.5, 0.55 * double(ln.MarkerSize));
            for pIdx = 1:numel(sx)
                if strcmp(ln.Marker, 'o')
                    svgLines{end+1} = sprintf( ...
                        '<circle cx="%.2f" cy="%.2f" r="%.2f" fill="%s" stroke="%s" stroke-width="1.4" pointer-events="none"/>', ...
                        sx(pIdx), sy(pIdx), mRad, rgbToHex(mFace), rgbToHex(mEdge)); %#ok<AGROW>
                else
                    svgLines{end+1} = sprintf( ...
                        '<rect x="%.2f" y="%.2f" width="%.2f" height="%.2f" fill="%s" stroke="%s" stroke-width="1.4" pointer-events="none"/>', ...
                        sx(pIdx)-mRad, sy(pIdx)-mRad, 2*mRad, 2*mRad, rgbToHex(mFace), rgbToHex(mEdge)); %#ok<AGROW>
                end
            end
        end
    end

    % 7. Serialize All Text Labels & Callout Badges ( Plus Exact Bounding Boxes for Avoidance)
    svgTexts = {};
    lblBBoxes = zeros(0, 4); % [svgX1, svgX2, svgY1, svgY2] for JS collision avoidance
    for t = 1:numel(txtList)
        tx = txtList(t);
        if ~strcmpi(tx.Units, 'data'), continue; end

        pos   = double(tx.Position);
        ext   = double(tx.Extent); % [xLeft, yBottom, w, h] in axes data units
        lines = formatTextLines(tx.String);
        if isempty(lines), continue; end

        sx1 = toSvgX(ext(1));
        sx2 = toSvgX(ext(1) + ext(3));
        sy1 = toSvgY(ext(2) + ext(4)); % Top in SVG
        sy2 = toSvgY(ext(2));          % Bottom in SVG

        % Record label bounding box if it sits above the bottom J-axis line
        if ext(3) > 0 && (ext(2) > yl(1) + 0.16 * diff(yl))
            lblBBoxes(end+1, :) = round([sx1, sx2, sy1, sy2], 1); %#ok<AGROW>
        end

        % Optional background box (e.g., Childhood|Adult badge or Net Fiscal Surplus badge)
        bgCol   = tx.BackgroundColor;
        edgeCol = tx.EdgeColor;
        if isnumeric(bgCol) && numel(bgCol) == 3
            strokeStr = 'none';
            if isnumeric(edgeCol) && numel(edgeCol) == 3
                strokeStr = rgbToHex(edgeCol);
            end
            padBox = 4;
            svgTexts{end+1} = sprintf( ...
                '<rect x="%.2f" y="%.2f" width="%.2f" height="%.2f" rx="2" fill="%s" stroke="%s" stroke-width="1.1" pointer-events="none"/>', ...
                sx1 - padBox, sy1 - padBox, (sx2 - sx1) + 2*padBox, (sy2 - sy1) + 2*padBox, ...
                rgbToHex(bgCol), strokeStr); %#ok<AGROW>
        end

        % Text alignment & multi-line <tspan> rendering
        anchor = 'start';
        txX    = toSvgX(pos(1));
        if strcmpi(tx.HorizontalAlignment, 'center')
            anchor = 'middle';
        elseif strcmpi(tx.HorizontalAlignment, 'right')
            anchor = 'end';
        end

        fSize   = max(10.5, 1.32 * double(tx.FontSize));
        lineH   = 1.22 * fSize;
        totH    = numel(lines) * lineH;
        posSvgY = toSvgY(pos(2));

        if strcmpi(tx.VerticalAlignment, 'bottom')
            startY = posSvgY - totH + 0.85 * fSize;
        elseif strcmpi(tx.VerticalAlignment, 'top')
            startY = posSvgY + 0.85 * fSize;
        else
            startY = posSvgY - 0.5 * totH + 0.82 * fSize;
        end

        fw = '400';
        if strcmpi(tx.FontWeight, 'bold'), fw = '700'; end
        colHex = rgbToHex(tx.Color);

        isNodeLbl = any(blkLblIdx == t);
        clsAttr   = 'sankey-text';
        if isNodeLbl, clsAttr = 'sankey-text node-label'; end

        tspans = {};
        for lineIdx = 1:numel(lines)
            dyVal = 0;
            if lineIdx > 1, dyVal = lineH; end
            tspans{end+1} = sprintf('<tspan x="%.2f" dy="%.2f">%s</tspan>', ...
                txX, dyVal, htmlEscape(lines{lineIdx})); %#ok<AGROW>
        end

        svgTexts{end+1} = sprintf( ...
            '<text id="lbl_%d" class="%s" x="%.2f" y="%.2f" text-anchor="%s" font-size="%.1fpx" font-weight="%s" fill="%s" data-orig-weight="%s" data-orig-color="%s" pointer-events="none">%s</text>', ...
            t, clsAttr, txX, startY, anchor, fSize, fw, colHex, fw, colHex, strjoin(tspans, '')); %#ok<AGROW>
    end

    % 8. Package Metadata Payload as JSON for the Embedded JS Engine
    payload = struct();
    payload.svgW       = svgW;
    payload.svgH       = svgH;
    payload.isFates17  = (nBlocks == 17);
    payload.xSplitSvg  = toSvgX(4.0);
    payload.minYSvg    = toSvgY(yl(1) + 0.92 * diff(yl)); % Top ceiling in SVG
    payload.maxYSvg    = toSvgY(yl(1) + 0.16 * diff(yl)); % Hard floor above J-axis in SVG!
    payload.gateXSvg   = round(toSvgX(1:6), 1);
    payload.blkGateCol = blkGateCol(:)';
    payload.blkYMid    = round(blkYMid(:)', 3);
    payload.lblBBoxes  = lblBBoxes;
    payload.ribbons    = ribbonsData;

    jsonPayload = jsonencode(payload);

    % 9. Assemble Self-Contained HTML5 Document
    htmlStr = buildStandaloneHTMLDocument(chartTitle, svgW, svgH, ...
        strjoin(svgDefs, newline), ...
        strjoin(svgRibbons, newline), ...
        strjoin(svgBlocks, newline), ...
        strjoin(svgLines, newline), ...
        strjoin(svgTexts, newline), ...
        jsonPayload);

    fid = fopen(outHtmlFile, 'w', 'n', 'UTF-8');
    if fid ~= -1
        fwrite(fid, htmlStr, 'char');
        fclose(fid);
        fprintf('  -> Exported interactive HTML5 Sankey to: %s\n', outHtmlFile);
    else
        warning('exportSankeyToHTML:FileOpenFailed', 'Could not write to %s', outHtmlFile);
    end
end

% =========================================================================
%  HTML5 + CSS + VANILLA JS TEMPLATE BUILDER
% =========================================================================
function htmlOut = buildStandaloneHTMLDocument(chartTitle, svgW, svgH, defsStr, ribsStr, blksStr, linesStr, txtsStr, jsonStr)
    cssBlock = [ ...
        'body { margin: 0; padding: 12px 18px; background: #f4f6f9; font-family: Helvetica, Arial, sans-serif; color: #111; user-select: none; }' newline ...
        '.header-bar { display: flex; justify-content: space-between; align-items: center; max-width: 1850px; margin: 0 auto 8px auto; }' newline ...
        '.chart-title { font-size: 16px; font-weight: 700; color: #141824; margin: 0; }' newline ...
        '.help-pill { font-size: 12px; color: #445; background: #e8eef5; border: 1px solid #c5d2e0; border-radius: 4px; padding: 4px 10px; }' newline ...
        '.stage-wrap { position: relative; max-width: 1850px; margin: 0 auto; background: #ffffff; border: 1px solid #d8dee9; border-radius: 6px; box-shadow: 0 3px 12px rgba(0,0,0,0.06); overflow: hidden; }' newline ...
        'svg { display: block; width: 100%; height: auto; cursor: default; }' newline ...
        '.sankey-ribbon { cursor: pointer; transition: fill-opacity 0.12s ease; }' newline ...
        '.sankey-ribbon:hover { fill-opacity: 0.72; }' newline ...
        '.sankey-block { cursor: pointer; }' newline ...
        '#hover-box { position: absolute; display: none; max-width: 410px; min-width: 270px; padding: 9px 12px; border: 2px solid #2b6cb0; border-radius: 4px; background: #fafcff; color: #14141a; font-size: 12.2px; line-height: 1.38; box-shadow: 0 4px 14px rgba(0,0,0,0.13); pointer-events: none; z-index: 20; box-sizing: border-box; }' newline ...
        '#hover-box .hb-hdr { font-weight: 700; margin-bottom: 4px; color: #0d1b2a; }' newline ...
        '#hover-box .hb-row { margin: 2px 0; }' newline ...
        '#hover-box .hb-cit { margin: 1px 0 1px 14px; color: #2b3a4a; font-size: 11.6px; }' ...
    ];

    jsBlock = [ ...
        'const DATA = JSON.parse(document.getElementById("sankey-data").textContent);' newline ...
        'const svgEl = document.getElementById("sankey-svg");' newline ...
        'const stageEl = document.getElementById("stage-wrap");' newline ...
        'const hoverBox = document.getElementById("hover-box");' newline ...
        'const leaderLine = document.getElementById("leader-line");' newline ...
        'const anchorDot = document.getElementById("anchor-dot");' newline ...
        'let activeIdx = 0; let anchorBlk = 1; let anchorSide = "src";' newline ...
        '' newline ...
        'function rgbCss(arr, alpha) {' newline ...
        '  if (alpha !== undefined) return `rgba(${arr[0]},${arr[1]},${arr[2]},${alpha})`;' newline ...
        '  return `rgb(${arr[0]},${arr[1]},${arr[2]})`;' newline ...
        '}' newline ...
        '' newline ...
        'function clearSelection() {' newline ...
        '  activeIdx = 0;' newline ...
        '  document.querySelectorAll(".sankey-ribbon").forEach(el => el.setAttribute("fill-opacity", "0.45"));' newline ...
        '  document.querySelectorAll(".node-label").forEach(el => {' newline ...
        '    el.setAttribute("font-weight", el.getAttribute("data-orig-weight") || "400");' newline ...
        '    el.setAttribute("fill", el.getAttribute("data-orig-color") || "#111");' newline ...
        '  });' newline ...
        '  hoverBox.style.display = "none";' newline ...
        '  leaderLine.setAttribute("visibility", "hidden");' newline ...
        '  anchorDot.setAttribute("visibility", "hidden");' newline ...
        '}' newline ...
        '' newline ...
        'function selectRibbon(hitIdx, refSvgX) {' newline ...
        '  const rib = DATA.ribbons[hitIdx - 1];' newline ...
        '  if (!rib) return;' newline ...
        '  activeIdx = hitIdx;' newline ...
        '' newline ...
        '  // 1. Spotlight active ribbon & dim background ribbons' newline ...
        '  document.querySelectorAll(".sankey-ribbon").forEach(el => {' newline ...
        '    const idx = parseInt(el.getAttribute("data-idx"), 10);' newline ...
        '    el.setAttribute("fill-opacity", idx === hitIdx ? "0.92" : "0.12");' newline ...
        '  });' newline ...
        '' newline ...
        '  // 2. Bold Source & Target labels, softly fade unselected labels' newline ...
        '  document.querySelectorAll(".node-label").forEach(el => {' newline ...
        '    const idNum = parseInt(el.id.replace("lbl_", ""), 10);' newline ...
        '    if (idNum === rib.srcLbl || idNum === rib.tgtLbl) {' newline ...
        '      el.setAttribute("font-weight", "700");' newline ...
        '      el.setAttribute("fill", "#080808");' newline ...
        '    } else {' newline ...
        '      el.setAttribute("font-weight", el.getAttribute("data-orig-weight") || "400");' newline ...
        '      el.setAttribute("fill", "#6e7785");' newline ...
        '    }' newline ...
        '  });' newline ...
        '' newline ...
        '  // 3. Find slice sIdx along rib.svgX' newline ...
        '  const xg = rib.svgX; const N = xg.length;' newline ...
        '  let sIdx = 0; let bestD = 1e9;' newline ...
        '  for (let i = 0; i < N; i++) {' newline ...
        '    const d = Math.abs(xg[i] - refSvgX);' newline ...
        '    if (d < bestD) { bestD = d; sIdx = i; }' newline ...
        '  }' newline ...
        '  const iMin = Math.max(1, Math.round(0.16 * N));' newline ...
        '  const iMax = Math.min(N - 2, Math.round(0.84 * N));' newline ...
        '  sIdx = Math.min(Math.max(sIdx, iMin), iMax);' newline ...
        '' newline ...
        '  const xPin = xg[sIdx];' newline ...
        '  const yPin = rib.svgYMid[sIdx];' newline ...
        '  const wFrac = sIdx / Math.max(1, N - 1);' newline ...
        '  const cLoc = [' newline ...
        '    Math.round((1 - wFrac) * rib.cS[0] + wFrac * rib.cT[0]),' newline ...
        '    Math.round((1 - wFrac) * rib.cS[1] + wFrac * rib.cT[1]),' newline ...
        '    Math.round((1 - wFrac) * rib.cS[2] + wFrac * rib.cT[2])' newline ...
        '  ];' newline ...
        '  const cBorder = cLoc.map(v => Math.round(0.76 * v));' newline ...
        '  const cBg = cLoc.map(v => Math.round(0.91 * 255 + 0.09 * v));' newline ...
        '' newline ...
        '  // 4. Populate HTML narrative box & measure its exact size in SVG units' newline ...
        '  hoverBox.innerHTML = rib.html;' newline ...
        '  hoverBox.style.borderColor = rgbCss(cBorder);' newline ...
        '  hoverBox.style.backgroundColor = rgbCss(cBg);' newline ...
        '  hoverBox.style.display = "block";' newline ...
        '' newline ...
        '  const scaleX = DATA.svgW / stageEl.clientWidth;' newline ...
        '  const scaleY = DATA.svgH / stageEl.clientHeight;' newline ...
        '  const boxW = hoverBox.offsetWidth * scaleX;' newline ...
        '  const boxH = hoverBox.offsetHeight * scaleY;' newline ...
        '' newline ...
        '  const pos = computeOptimalBoxPosition(rib, xPin, yPin, boxW, boxH);' newline ...
        '  hoverBox.style.left = `${(pos.boxX / DATA.svgW) * 100}%`;' newline ...
        '  hoverBox.style.top  = `${(pos.boxY / DATA.svgH) * 100}%`;' newline ...
        '' newline ...
        '  leaderLine.setAttribute("x1", xPin);' newline ...
        '  leaderLine.setAttribute("y1", yPin);' newline ...
        '  leaderLine.setAttribute("x2", pos.attachX);' newline ...
